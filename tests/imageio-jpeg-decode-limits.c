static CGImageRef decode(const unsigned char *bytes, size_t length, CFDataRef *keep) {
    CFDataRef data = CFDataCreate(NULL, bytes, (CFIndex) length);
    CGImageSourceRef source = CGImageSourceCreateWithData(data, NULL);
    CGImageRef image = source ? CGImageSourceCreateImageAtIndex(source, 0, NULL) : NULL;
    if (source != NULL)
        CFRelease(source);
    *keep = data;
    return image;
}

static void checkDecodes(const char *name, const unsigned char *bytes, size_t length, int checkValues) {
    CFDataRef data;
    CGImageRef image = decode(bytes, length, &data);
    CHECK(image != NULL, name);
    if (image != NULL) {
        CHECK(CGImageGetWidth(image) == 3, name);
        CHECK(CGImageGetHeight(image) == 7, name);
        CFDataRef pixels = CGDataProviderCopyData(CGImageGetDataProvider(image));
        CHECK(pixels != NULL, name);
        if (pixels != NULL) {
            size_t rowBytes = CGImageGetBytesPerRow(image);
            size_t pixelBytes = CGImageGetBitsPerPixel(image) / 8;
            CHECK(pixelBytes >= 3 && CFDataGetLength(pixels) >= (CFIndex) (6 * rowBytes + 3 * pixelBytes),
                  "pixel layout");
            if (pixelBytes >= 3 && CFDataGetLength(pixels) >= (CFIndex) (6 * rowBytes + 3 * pixelBytes)) {
                const unsigned char *p = CFDataGetBytePtr(pixels);
                for (size_t y = 0; y < 7; y++) {
                    for (size_t x = 0; x < 3; x++) {
                        const unsigned char *px = p + y * rowBytes + x * pixelBytes;
                        if (checkValues)
                            CHECK(px[0] == 200 && px[1] == 100 && px[2] == 50, "pixel value");
                    }
                }
            }
            CFRelease(pixels);
        }
        CGImageRelease(image);
    }
    CFRelease(data);
    printf("%s: decoded\n", name);
    fflush(stdout);
}

static void checkRejected(const char *name, const unsigned char *bytes, size_t length) {
    CFDataRef data;
    CGImageRef image = decode(bytes, length, &data);
    CHECK(image == NULL, name);
    if (image != NULL)
        CGImageRelease(image);
    CFRelease(data);
    printf("%s: rejected without crashing\n", name);
    fflush(stdout);
}

int main(void) {
    checkDecodes("CMYK 3x7", kCMYKJPEG, sizeof(kCMYKJPEG), 0);
    checkDecodes("RGB 3x7", kRGBJPEG, sizeof(kRGBJPEG), 1);
    checkRejected("declared 32768x32768", kHuge32768, sizeof(kHuge32768));
    checkRejected("declared 65500x65500", kHuge65500, sizeof(kHuge65500));
    checkRejected("declared 10001x10000", kOverCap, sizeof(kOverCap));
    checkDecodes("CMYK 3x7 after the rejections", kCMYKJPEG, sizeof(kCMYKJPEG), 0);

    if (failures == 0)
        puts("PASS JPEG decode handles odd heights, CMYK and absurd declared sizes");
    return failures != 0;
}
