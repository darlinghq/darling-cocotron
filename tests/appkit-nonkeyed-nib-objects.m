 *
 * Non-keyed (NSArchiver / typedstream) decoding of the nib object classes:
 * NSWindowTemplate, NSCustomObject, NSCustomView, NSIBObjectData and the nib
 * connectors.
 *
 * Two kinds of checks:
 *  - A scripted NSCoder (allowsKeyedCoding NO) answers the public decode calls
 *    and records them. The expected call sequences and the version gates are
 *    those observed on Mac OS X 10.14.4 with a recording coder of the same
 *    shape (black-box, public NSCoder calls only). What a value means (which
 *    flag byte is which window flag, which object is the class name) was
 *    established the same way, by changing one decoded value at a time and
 *    reading the result through accessors.
 *  - Archives written by NSArchiver on Mac OS X 10.14.4 and macOS 26.7.3
 *    (tests/fixtures/nonkeyed, generated by mkfix.m there) are unarchived with
 *    NSUnarchiver.
 * The program only uses the runtime to reach the private classes, so it builds
 * and runs on macOS too, where the same expectations hold for everything that
 * the Mac archived.
 *
 * Usage: appkit-nonkeyed-nib-objects <tests/fixtures/nonkeyed> [--mac <fixture set>]
 * (--mac: running on macOS: skip the checks of versions macOS itself crashes on,
 * and unarchive only the named fixture set, written by that macOS version;
 * a Mac can not read archives of a newer system)
 */
#import <AppKit/AppKit.h>
#import <objc/runtime.h>
#import <objc/message.h>
#include <stdarg.h>
#include <stdio.h>

static int failures;

static void expect(BOOL ok, const char *what)
{
    if (!ok) {
        fprintf(stderr, "FAIL: %s\n", what);
        failures++;
    }
}

static void expectString(NSString *got, NSString *want, const char *what)
{
    if (got != want && ![got isEqual: want]) {
        fprintf(stderr, "FAIL: %s: got '%s', want '%s'\n", what,
                [[got description] UTF8String], [[want description] UTF8String]);
        failures++;
    }
}

// A scripted coder. Values come from the spec dictionary keyed by kind letter
// and index of the value among the values of that kind decoded so far: "c0",
// "i1", "f3", "o2" (objects and object-typed values), "x0" (anything else).
@interface Scripted : NSCoder {
@public
    NSMutableDictionary *spec;
    NSMutableArray *log;
    NSString *under;
    NSInteger version;
    int counts[256];
}
@end

@implementation Scripted
- (BOOL) allowsKeyedCoding
{
    return NO;
}

- (NSInteger) versionForClassName: (NSString *) name
{
    [log addObject: [@"v?" stringByAppendingString: name]];
    if ([name isEqualToString: under]) {
        return version;
    }
    Class c = NSClassFromString(name);
    return c ? (NSInteger) [c version] : 0;
}

static char kindOf(const char *t)
{
    switch (t[0]) {
        case '@': return 'o';
        case 'c': return 'c';
        case 'i': return 'i';
        case 'f': return 'f';
        default: return 'x';
    }
}

- (void) store: (const char *) t at: (void *) p
{
    char k = kindOf(t);
    int idx = counts[(unsigned char) k]++;
    id v = [spec objectForKey: [NSString stringWithFormat: @"%c%d", k, idx]];

    switch (t[0]) {
        case 'c': *(char *) p = [v charValue]; break;
        case 'i': *(int *) p = [v intValue]; break;
        case 'f': *(float *) p = [v floatValue]; break;
        case '@': *(id *) p = [v retain]; break;
        case '*': *(char *) p = 0; *(char **) p = v ? strdup([v UTF8String]) : NULL; break;
        default: {
            NSUInteger size;
            NSGetSizeAndAlignment(t, &size, NULL);
            memset(p, 0, size);
        }
    }
}

- (void) decodeValueOfObjCType: (const char *) t at: (void *) p
{
    [log addObject: [NSString stringWithUTF8String: t]];
    [self store: t at: p];
}

- (void) decodeValuesOfObjCTypes: (const char *) t, ...
{
    va_list ap;
    NSMutableString *entry = [NSMutableString stringWithString: @"multi:"];

    va_start(ap, t);
    while (*t) {
        NSUInteger size;
        const char *next = NSGetSizeAndAlignment(t, &size, NULL);
        void *p = va_arg(ap, void *);

        [entry appendFormat: @"%.*s,", (int) (next - t), t];
        [self store: t at: p];
        t = next;
    }
    va_end(ap);
    [log addObject: entry];
}

- (id) decodeObject
{
    [log addObject: @"obj"];
    int idx = counts['o']++;
    return [spec objectForKey: [NSString stringWithFormat: @"o%d", idx]];
}
@end

static Scripted *scripted(NSString *cls, NSInteger version, NSDictionary *spec)
{
    Scripted *s = [[[Scripted alloc] init] autorelease];
    s->spec = [[spec mutableCopy] autorelease];
    s->log = [NSMutableArray array];
    s->under = cls;
    s->version = version;
    return s;
}

static NSString *seq(Scripted *s)
{
    return [s->log componentsJoinedByString: @" "];
}

#define N(x) [NSNumber numberWithInt: (x)]
#define F(x) [NSNumber numberWithFloat: (x)]

static long ask(id o, const char *sel)
{
    SEL s = sel_registerName(sel);
    if (![o respondsToSelector: s]) {
        return -999;
    }
    return (long) ((long (*)(id, SEL)) objc_msgSend)(o, s);
}

static id ivarObject(id o, const char *name1, const char *name2)
{
    Ivar iv = class_getInstanceVariable([o class], name1);
    if (iv == NULL) {
        iv = class_getInstanceVariable([o class], name2);
    }
    // A plain read: object_getIvar would go through the weak-reference machinery for
    // instance variables the class declares weak.
    return iv ? *(id *) ((char *) o + ivar_getOffset(iv)) : nil;
}

static unsigned flagWord(id o)
{
    Ivar iv = class_getInstanceVariable([o class], "_wtFlags");
    return iv ? *(unsigned *) ((char *) o + ivar_getOffset(iv)) : 0xdeadbeef;
}

// Reads a size-valued instance variable of a private class.
static NSSize sizeIvar(id o, const char *name1, const char *name2)
{
    Ivar iv = class_getInstanceVariable([o class], name1);
    if (iv == NULL) {
        iv = class_getInstanceVariable([o class], name2);
    }
    if (iv == NULL) {
        return NSMakeSize(-1, -1);
    }
    return *(NSSize *) ((char *) o + ivar_getOffset(iv));
}

// Decodes class `cls` from a scripted coder; returns nil and sets *reason on an exception.
static id decodeWith(Scripted *coder, NSString *cls, NSString **reason)
{
    id result = nil;
    @try {
        result = [[NSClassFromString(cls) alloc] initWithCoder: coder];
    } @catch (NSException *e) {
        if (reason) {
            *reason = [e reason];
        }
    }
    return [result autorelease];
}

// Stops an unarchived NSWindowTemplate from turning itself into a window, which
// needs a window server and is not what these tests look at.
static id keepTemplate(id self, SEL _cmd, id coder)
{
    return self;
}

static void testCustomObject(void)
{
    NSDictionary *spec = [NSDictionary dictionaryWithObjectsAndKeys: @"MyClass", @"o0", @"ext", @"o1", nil];
    NSString *reason = nil;
    Scripted *s;
    id o;

    // Versions 1-16 and 41 and later: both objects in one call.
    for (NSNumber *v in [NSArray arrayWithObjects: N(1), N(16), N(41), N(43), nil]) {
        s = scripted(@"NSCustomObject", [v intValue], spec);
        o = decodeWith(s, @"NSCustomObject", &reason);
        expectString(seq(s), @"v?NSCustomObject multi:@,@,", "NSCustomObject sequence");
        expectString(ivarObject(o, "className", "_className"), @"MyClass", "NSCustomObject class name");
        expectString(ivarObject(o, "extension", "_extension"), @"ext", "NSCustomObject extension");
    }

    // Versions 17-40: two separate objects, class name first.
    for (NSNumber *v in [NSArray arrayWithObjects: N(17), N(30), N(40), nil]) {
        s = scripted(@"NSCustomObject", [v intValue], spec);
        o = decodeWith(s, @"NSCustomObject", &reason);
        expectString(seq(s), @"v?NSCustomObject obj obj", "NSCustomObject 17-40 sequence");
        expectString(ivarObject(o, "className", "_className"), @"MyClass", "NSCustomObject 17-40 class name");
        expectString(ivarObject(o, "extension", "_extension"), @"ext", "NSCustomObject 17-40 extension");
    }

    // Version 0: a C string class name, then an object.
    s = scripted(@"NSCustomObject", 0, [NSDictionary dictionaryWithObjectsAndKeys: @"OldClass", @"o0", @"ext", @"o1", nil]);
    o = decodeWith(s, @"NSCustomObject", &reason);
    expectString(seq(s), @"v?NSCustomObject multi:*,@,", "NSCustomObject version 0 sequence");
    expect(o != nil, "NSCustomObject version 0 decodes");
}

// Set by "--mac": skips the checks of versions the Mac itself crashes on.
static int onMac;

static void testWindowTemplate(void)
{
    NSString *reason = nil;
    Scripted *s;
    id t;
    NSDictionary *spec;

    // Versions 17-40: style, backing, rect, eleven flag bytes, five objects.
    spec = [NSDictionary dictionaryWithObjectsAndKeys:
        N(15), @"i0", N(2), @"i1", F(10), @"f0", F(20), @"f1", F(300), @"f2", F(200), @"f3",
        @"Title", @"o0", @"NSWindow", @"o1", nil];
    s = scripted(@"NSWindowTemplate", 30, spec);
    t = decodeWith(s, @"NSWindowTemplate", &reason);
    expectString(seq(s),
        @"v?NSWindowTemplate multi:i,i, multi:f,f,f,f, multi:c, multi:c, multi:c, multi:c, multi:c, multi:c, multi:c, multi:c, multi:c, multi:c, c obj obj obj obj obj",
        "NSWindowTemplate 17-40 sequence");
    expect(t != nil, "NSWindowTemplate 17-40 decodes");

    // Which byte sets which bit of the flag word (one byte at a time). Bit 14, the
    // flag for automatically setting the miniaturizable style, is set by this layout
    // whatever the bytes are.
    {
        static const struct { const char *key; unsigned bits; } bytes[] = {
            { "c0", 0x80000000u }, { "c1", 0x40000000u }, { "c2", 0x20000000u }, { "c3", 0x10000000u },
            { "c4", 0x08000000u }, { "c5", 0x04000000u }, { "c6", 0x02000000u }, { "c7", 0x00080000u },
            { "c8", 0x00040000u }, { "c9", 0 }, { "c10", 0 },
        };
        for (size_t i = 0; i < sizeof(bytes) / sizeof(bytes[0]); i++) {
            NSMutableDictionary *one = [[spec mutableCopy] autorelease];
            [one setObject: N(1) forKey: [NSString stringWithUTF8String: bytes[i].key]];
            s = scripted(@"NSWindowTemplate", 30, one);
            t = decodeWith(s, @"NSWindowTemplate", &reason);
            unsigned got = flagWord(t) & ~0x200u; // bit 9 (restorable) follows the window style, not the bytes
            if (got != (bytes[i].bits | 0x4000u)) {
                fprintf(stderr, "FAIL: NSWindowTemplate 17-40 byte %s: flag word %08x, want %08x\n", bytes[i].key,
                        got, bytes[i].bits | 0x4000u);
                failures++;
            }
        }
    }
    {
        NSMutableDictionary *mask = [[spec mutableCopy] autorelease];
        [mask setObject: N(0x2a) forKey: @"c7"];
        s = scripted(@"NSWindowTemplate", 40, mask);
        t = decodeWith(s, @"NSWindowTemplate", &reason);
        expect(ask(t, "autoPositionMask") == 0x2a, "NSWindowTemplate auto-position byte is the mask");
        expect(ask(t, "hidesOnDeactivate") == 0, "NSWindowTemplate unset flag bytes stay clear");
    }
    {
        NSMutableDictionary *all = [[spec mutableCopy] autorelease];
        for (int i = 0; i < 11; i++) {
            [all setObject: N(1) forKey: [NSString stringWithFormat: @"c%d", i]];
        }
        s = scripted(@"NSWindowTemplate", 30, all);
        t = decodeWith(s, @"NSWindowTemplate", &reason);
        expect(ask(t, "hidesOnDeactivate") == 1 && ask(t, "isReleasedWhenClosed") == 0 && ask(t, "isOneShot") == 1
                    && ask(t, "isDeferred") == 1 && ask(t, "wantsToBeColor") == 1,
               "NSWindowTemplate window flag accessors from the flag bytes");
    }

    // Versions 41 and 42: flags word, screen-rect flag, minimum-size byte. Nothing more.
    s = scripted(@"NSWindowTemplate", 41, spec);
    decodeWith(s, @"NSWindowTemplate", &reason);
    expectString(seq(s), @"v?NSWindowTemplate multi:i,i,f,f,f,f,i,@,@,@,@,@,c, c", "NSWindowTemplate 41 sequence");
    s = scripted(@"NSWindowTemplate", 42, spec);
    decodeWith(s, @"NSWindowTemplate", &reason);
    expectString(seq(s), @"v?NSWindowTemplate multi:i,i,f,f,f,f,i,@,@,@,@,@,c, c", "NSWindowTemplate 42 sequence");

    // Version 43 and later: autosave name and maximum-size byte follow. The screen
    // rectangle is only stored when the flag byte is non-zero.
    s = scripted(@"NSWindowTemplate", 504, spec);
    decodeWith(s, @"NSWindowTemplate", &reason);
    expectString(seq(s), @"v?NSWindowTemplate multi:i,i,f,f,f,f,i,@,@,@,@,@,c, c obj c", "NSWindowTemplate 504 sequence");

    NSMutableDictionary *full = [[spec mutableCopy] autorelease];
    [full setObject: N(1) forKey: @"c0"];             // screen rect follows
    [full setObject: F(0) forKey: @"f4"];
    [full setObject: F(0) forKey: @"f5"];
    [full setObject: F(1440) forKey: @"f6"];
    [full setObject: F(900) forKey: @"f7"];
    [full setObject: N(1) forKey: @"c1"];             // minimum size follows
    [full setObject: F(120) forKey: @"f8"];
    [full setObject: F(80) forKey: @"f9"];
    [full setObject: @"Autosave" forKey: @"o5"];
    [full setObject: N(3) forKey: @"c2"];             // maximum size follows; bit 0 is not looked at here
    [full setObject: F(640) forKey: @"f10"];
    [full setObject: F(480) forKey: @"f11"];
    s = scripted(@"NSWindowTemplate", 504, full);
    t = decodeWith(s, @"NSWindowTemplate", &reason);
    expectString(seq(s),
        @"v?NSWindowTemplate multi:i,i,f,f,f,f,i,@,@,@,@,@,c, multi:f,f,f,f, c multi:f,f, obj c multi:f,f,",
        "NSWindowTemplate full sequence");
    {
        NSSize minSize = sizeIvar(t, "minSize", "_minSize");
        NSSize maxSize = sizeIvar(t, "maxSize", "_maxSize");
        expect(minSize.width == 120 && minSize.height == 80, "NSWindowTemplate minimum size");
        expect(maxSize.width == 640 && maxSize.height == 480, "NSWindowTemplate maximum size");
    }

    // Versions below 17 are not supported (the Mac crashes on them with this coder).
    if (!onMac) {
        reason = nil;
        s = scripted(@"NSWindowTemplate", 16, spec);
        t = decodeWith(s, @"NSWindowTemplate", &reason);
        expect(t == nil && reason != nil, "NSWindowTemplate version 16 is rejected");
    }
}

static void testIBObjectData(void)
{
    NSString *reason = nil;
    id owner = [[[NSObject alloc] init] autorelease];
    id key = @"objectKey", value = @"objectValue", nameKey = @"nameKey", nameValue = @"nameValue";
    NSSet *visible = [NSSet setWithObject: @"window"];
    NSArray *connections = [NSArray array];
    NSDictionary *spec = [NSDictionary dictionaryWithObjectsAndKeys:
        owner, @"o0", N(1), @"i0", key, @"o1", value, @"o2", N(1), @"i1", nameKey, @"o3", nameValue, @"o4",
        visible, @"o5", connections, @"o6", N(1), @"i2", @"oidKey", @"o8", N(9), @"i3", N(20), @"i4",
        N(0), @"i5", @"Framework", @"o9", nil];
    Scripted *s;
    id d;

    // Version 24 (without framework) and 224 (with): the layout of 10.14.4.
    s = scripted(@"NSIBObjectData", 24, spec);
    d = decodeWith(s, @"NSIBObjectData", &reason);
    expectString(seq(s), @"v?NSIBObjectData @ i multi:@,@, i multi:@,@, @ @ @ i multi:@,i, i i",
        "NSIBObjectData 24 sequence");
    expect(d != nil, "NSIBObjectData 24 decodes");
    expect(ask(d, "rootObject") == (long) owner, "NSIBObjectData root object");
    expect([[d valueForKey: @"objectTable"] count] == 1, "NSIBObjectData object table");
    expect([[d valueForKey: @"nameTable"] count] == 1, "NSIBObjectData name table");

    s = scripted(@"NSIBObjectData", 224, spec);
    d = decodeWith(s, @"NSIBObjectData", &reason);
    expectString(seq(s), @"v?NSIBObjectData @ i multi:@,@, i multi:@,@, @ @ @ i multi:@,i, i i multi:@,",
        "NSIBObjectData 224 sequence");
    expectString([d valueForKey: @"targetFramework"], @"Framework", "NSIBObjectData framework from 224");

    // Zero values and nil objects (as the recording coder supplies) do not raise from 24 on.
    s = scripted(@"NSIBObjectData", 224, [NSDictionary dictionary]);
    d = decodeWith(s, @"NSIBObjectData", &reason);
    expect(d != nil, "NSIBObjectData decodes an empty archive");
    expectString(seq(s), @"v?NSIBObjectData @ i i @ @ @ i i i multi:@,", "NSIBObjectData empty sequence");

    // Versions 19-23 stop before the table of instantiated objects.
    s = scripted(@"NSIBObjectData", 20, [NSDictionary dictionary]);
    d = decodeWith(s, @"NSIBObjectData", &reason);
    expectString(seq(s), @"v?NSIBObjectData @ i i @ @ @ i i", "NSIBObjectData 20 sequence");
}

static void testConnectors(void)
{
    NSString *reason = nil;
    NSDictionary *spec = [NSDictionary dictionaryWithObjectsAndKeys: @"src", @"o0", @"dst", @"o1", @"label", @"o2", nil];

    for (NSString *cls in [NSArray arrayWithObjects: @"NSNibConnector", @"NSNibOutletConnector", @"NSNibControlConnector", nil]) {
        for (NSNumber *v in [NSArray arrayWithObjects: N(17), N(19), nil]) {
            Scripted *s = scripted(cls, [v intValue], spec);
            // The subclasses ask for their own version after the NSNibConnector part.
            if (![cls isEqualToString: @"NSNibConnector"]) {
                s->under = @"NSNibConnector";
                s->version = [v intValue];
            }
            id c = decodeWith(s, cls, &reason);
            expect(c != nil, "connector decodes");
            expectString(ivarObject(c, "_source", "source"), @"src", "connector source");
            expectString(ivarObject(c, "_destination", "destination"), @"dst", "connector destination");
            expectString(ivarObject(c, "_label", "label"),
                         [cls isEqualToString: @"NSNibControlConnector"] ? @"label:" : @"label", "connector label");
            NSString *want = [cls isEqualToString: @"NSNibConnector"]
                    ? @"v?NSNibConnector multi:@,@,@,"
                    : [NSString stringWithFormat: @"v?NSNibConnector multi:@,@,@, v?%@", cls];
            if ([cls isEqualToString: @"NSNibConnector"]) {
                expectString(seq(s), want, "NSNibConnector sequence");
            }
        }
    }
}

static id unarchive(NSString *dir, NSString *name)
{
    NSData *data = [NSData dataWithContentsOfFile: [dir stringByAppendingPathComponent: name]];
    if (data == nil) {
        return nil;
    }
    id result = nil;
    @try {
        result = [NSUnarchiver unarchiveObjectWithData: data];
    } @catch (NSException *e) {
        fprintf(stderr, "FAIL: unarchiving %s raised %s\n", [name UTF8String], [[e reason] UTF8String]);
        failures++;
    }
    return result;
}

static void testFixtures(NSString *dir)
{
    NSString *where = [dir lastPathComponent];
    id o;

    o = unarchive(dir, @"customobject.typedstream");
    expect(o != nil && [NSStringFromClass([o class]) isEqualToString: @"NSCustomObject"], "custom object fixture class");
    expectString(ivarObject(o, "className", "_className"), @"FixtureOwner", "custom object fixture class name");
    expectString(ivarObject(o, "extension", "_extension"), @"ext", "custom object fixture extension");

    o = unarchive(dir, @"windowtemplate.typedstream");
    expect(o != nil && [NSStringFromClass([o class]) isEqualToString: @"NSWindowTemplate"], "window template fixture class");
    expect(ask(o, "hidesOnDeactivate") == 1, "window template fixture hides on deactivate");
    expect(ask(o, "isOneShot") == 1, "window template fixture one shot");
    expect(ask(o, "isDeferred") == 1, "window template fixture deferred");
    expect(ask(o, "isReleasedWhenClosed") == 0, "window template fixture not released when closed");
    {
        NSSize minSize = sizeIvar(o, "minSize", "_minSize");
        NSSize maxSize = sizeIvar(o, "maxSize", "_maxSize");
        expect(minSize.width == 120 && minSize.height == 80, "window template fixture minimum size");
        expect(maxSize.width == 640 && maxSize.height == 480, "window template fixture maximum size");
    }

    o = unarchive(dir, @"controlconnector.typedstream");
    expect(o != nil, "control connector fixture decodes");
    expectString(ivarObject(o, "_label", "label"), @"doIt:", "control connector fixture label");
    // The source and destination are not looked at: the connector does not own them
    // on macOS, and the unarchiver releases them when it finishes.

    if ([[NSFileManager defaultManager] fileExistsAtPath: [dir stringByAppendingPathComponent: @"outletconnector.typedstream"]]) {
        o = unarchive(dir, @"outletconnector.typedstream");
        expect(o != nil && [NSStringFromClass([o class]) isEqualToString: @"NSNibOutletConnector"], "outlet connector fixture class");
        expectString(ivarObject(o, "_label", "label"), @"someOutlet", "outlet connector fixture label");
    }

    o = unarchive(dir, @"customview.typedstream");
    // On macOS the custom view stays a placeholder holding the class name; here it
    // may already be the substituted view of that class.
    expect([o isKindOfClass: [NSView class]], "custom view fixture is a view");
    if ([NSStringFromClass([o class]) isEqualToString: @"NSCustomView"]) {
        expectString(ivarObject(o, "className", "_className"), @"NSTextView", "custom view fixture class name");
    }

    if ([[NSFileManager defaultManager] fileExistsAtPath: [dir stringByAppendingPathComponent: @"ibobjectdata.typedstream"]]) {
        o = unarchive(dir, @"ibobjectdata.typedstream");
        expect(o != nil && [NSStringFromClass([o class]) isEqualToString: @"NSIBObjectData"], "object data fixture class");
        expectString(ivarObject([o performSelector: @selector(rootObject)], "className", "_className"), @"FixtureOwner", "object data fixture root");
        expect([[o valueForKey: @"connections"] count] == 1, "object data fixture connection count");
    }
    (void) where;
}

int main(int argc, char **argv)
{
    NSAutoreleasePool *pool = [[NSAutoreleasePool alloc] init];
    {
        if (argc < 2) {
            fprintf(stderr, "usage: %s tests/fixtures/nonkeyed\n", argv[0]);
            return 2;
        }
        NSString *fixtures = [NSString stringWithUTF8String: argv[1]];
        onMac = argc > 2 && strcmp(argv[2], "--mac") == 0;

        class_replaceMethod(NSClassFromString(@"NSWindowTemplate"), @selector(awakeAfterUsingCoder:),
                            (IMP) keepTemplate, "@@:@");

        testCustomObject();
        testWindowTemplate();
        testIBObjectData();
        testConnectors();
        NSArray *sets = onMac && argc > 3 ? [NSArray arrayWithObject: [NSString stringWithUTF8String: argv[3]]]
                                          : [NSArray arrayWithObjects: @"mojave-10.14.4", @"macos-26.7.3", nil];
        for (NSString *name in sets) {
            testFixtures([fixtures stringByAppendingPathComponent: name]);
        }
    }
    [pool drain];
    if (failures) {
        fprintf(stderr, "%d failure(s)\n", failures);
        return 1;
    }
    printf("OK\n");
    return 0;
}
