/*
 * Copyright (C) 2026 Lubos Dolezel
 *
 * Non-keyed (NSArchiver / typedstream) decoding of NSView, NSControl,
 * NSActionCell and NSCell.
 *
 * Two kinds of checks:
 *  - A scripted NSCoder (allowsKeyedCoding NO) answers the public decode calls
 *    and records them. The expected call sequences and the version gates are
 *    those observed on Mac OS X 10.14.4 with a recording coder of the same
 *    shape (black-box, public NSCoder calls only). What a value means (which
 *    flag byte is which window flag, which object is the class name) was
 *    established the same way, by changing one decoded value at a time and
 *    reading the result through accessors.
 *  - Archives written by NSArchiver on Mac OS X 10.14.4 and macOS 26.7.3
 *    (tests/fixtures/nonkeyed, generated by mkfix.m there) are unarchived with
 *    NSUnarchiver.
 * The program only uses the runtime to reach the private classes, so it builds
 * and runs on macOS too, where the same expectations hold for everything that
 * the Mac archived.
 *
 * Usage: appkit-nonkeyed-view-control-cell <tests/fixtures/nonkeyed> [--mac <fixture set>]
 * (on macOS 26 only the fixtures are checked: it reads one layout for all versions)
 * (--mac: running on macOS: skip the checks of versions macOS itself crashes on,
 * and unarchive only the named fixture set, written by that macOS version;
 * a Mac can not read archives of a newer system)
 */
#import <AppKit/AppKit.h>
#import <objc/runtime.h>
#include <stdarg.h>
#include <stdio.h>

static int failures;

// Set by "--mac": running on macOS.
static int onMac;

static void expect(BOOL ok, const char *what)
{
    if (!ok) {
        fprintf(stderr, "FAIL: %s\n", what);
        failures++;
    }
}

static void expectString(NSString *got, NSString *want, const char *what)
{
    if (got != want && ![got isEqual: want]) {
        fprintf(stderr, "FAIL: %s: got '%s', want '%s'\n", what,
                [[got description] UTF8String], [[want description] UTF8String]);
        failures++;
    }
}

// A scripted coder. Values come from the spec dictionary keyed by kind letter
// and index of the value among the values of that kind decoded so far: "c0",
// "i1", "f3", "o2" (objects and object-typed values), "x0" (anything else).
@interface Scripted : NSCoder {
@public
    NSMutableDictionary *spec;
    NSMutableArray *log;
    NSString *under;
    NSInteger version;
    int counts[256];
}
@end

@implementation Scripted
- (BOOL) allowsKeyedCoding
{
    return NO;
}

- (NSInteger) versionForClassName: (NSString *) name
{
    [log addObject: [@"v?" stringByAppendingString: name]];
    if ([name isEqualToString: under]) {
        return version;
    }
    Class c = NSClassFromString(name);
    return c ? (NSInteger) [c version] : 0;
}

static char kindOf(const char *t)
{
    switch (t[0]) {
        case '@': return 'o';
        case 'c': return 'c';
        case 'i': return 'i';
        case 's': return 's';
        case 'f': return 'f';
        default: return 'x';
    }
}

- (void) store: (const char *) t at: (void *) p
{
    char k = kindOf(t);
    int idx = counts[(unsigned char) k]++;
    id v = [spec objectForKey: [NSString stringWithFormat: @"%c%d", k, idx]];

    switch (t[0]) {
        case 'c': *(char *) p = [v charValue]; break;
        case 'i': *(int *) p = [v intValue]; break;
        case 's': *(short *) p = (short) [v intValue]; break;
        case ':': *(SEL *) p = sel_registerName([[NSString stringWithFormat: @"sel%d:", idx] UTF8String]); break;
        case 'f': *(float *) p = [v floatValue]; break;
        case '@': *(id *) p = [v retain]; break;
        case '*': *(char *) p = 0; *(char **) p = v ? strdup([v UTF8String]) : NULL; break;
        default: {
            NSUInteger size;
            NSGetSizeAndAlignment(t, &size, NULL);
            memset(p, 0, size);
        }
    }
}

- (void) decodeValueOfObjCType: (const char *) t at: (void *) p
{
    [log addObject: [NSString stringWithUTF8String: t]];
    [self store: t at: p];
}

- (void) decodeValuesOfObjCTypes: (const char *) t, ...
{
    va_list ap;
    NSMutableString *entry = [NSMutableString stringWithString: @"multi:"];

    va_start(ap, t);
    while (*t) {
        NSUInteger size;
        const char *next = NSGetSizeAndAlignment(t, &size, NULL);
        void *p = va_arg(ap, void *);

        [entry appendFormat: @"%.*s,", (int) (next - t), t];
        [self store: t at: p];
        t = next;
    }
    va_end(ap);
    [log addObject: entry];
}

- (id) decodeObject
{
    [log addObject: @"obj"];
    int idx = counts['o']++;
    return [spec objectForKey: [NSString stringWithFormat: @"o%d", idx]];
}
@end

static Scripted *scripted(NSString *cls, NSInteger version, NSDictionary *spec)
{
    Scripted *s = [[[Scripted alloc] init] autorelease];
    s->spec = [[spec mutableCopy] autorelease];
    s->log = [NSMutableArray array];
    s->under = cls;
    s->version = version;
    return s;
}

static NSString *seq(Scripted *s)
{
    return [s->log componentsJoinedByString: @" "];
}

#define N(x) [NSNumber numberWithInt: (x)]
#define F(x) [NSNumber numberWithFloat: (x)]

static unsigned flagWord(id o)
{
    Ivar iv = class_getInstanceVariable([o class], "_wtFlags");
    return iv ? *(unsigned *) ((char *) o + ivar_getOffset(iv)) : 0xdeadbeef;
}

// Reads a size-valued instance variable of a private class.
static NSSize sizeIvar(id o, const char *name1, const char *name2)
{
    Ivar iv = class_getInstanceVariable([o class], name1);
    if (iv == NULL) {
        iv = class_getInstanceVariable([o class], name2);
    }
    if (iv == NULL) {
        return NSMakeSize(-1, -1);
    }
    return *(NSSize *) ((char *) o + ivar_getOffset(iv));
}

// Decodes class `cls` from a scripted coder; returns nil and sets *reason on an exception.
static id decodeWith(Scripted *coder, NSString *cls, NSString **reason)
{
    id result = nil;
    @try {
        result = [[NSClassFromString(cls) alloc] initWithCoder: coder];
    } @catch (NSException *e) {
        if (reason) {
            *reason = [e reason];
        }
    }
    return [result autorelease];
}

// Class versions are those of the Mac OS X 10.14 AppKit; this implementation does
// not set +version, and a scripted coder gets the value from there.
static void setCurrentVersions(void)
{
    if ([NSView version] == 0) {
        class_setVersion([NSView class], 41);
        class_setVersion([NSControl class], 41);
        class_setVersion([NSCell class], 65);
        class_setVersion([NSActionCell class], 17);
    }
}

static NSString *viewPrefix = @"obj v?NSView ";

static NSString *describeView(NSView *v)
{
    return [NSString stringWithFormat: @"frame=%@ bounds=%@ mask=%lu autoresizesSubviews=%d subviews=%lu",
            NSStringFromRect([v frame]), NSStringFromRect([v bounds]), (unsigned long) [v autoresizingMask],
            [v autoresizesSubviews], (unsigned long) [[v subviews] count]];
}

static void testView(void)
{
    NSString *reason = nil;
    NSView *superview = [[[NSView alloc] initWithFrame: NSMakeRect(0, 0, 51, 10)] autorelease];
    NSView *nextKey = [[[NSView alloc] initWithFrame: NSMakeRect(0, 0, 77, 10)] autorelease];
    NSMutableDictionary *base = [NSMutableDictionary dictionaryWithObjectsAndKeys:
        F(1), @"f0", F(2), @"f1", F(30), @"f2", F(40), @"f3", F(5), @"f4", F(6), @"f5", F(70), @"f6", F(80), @"f7",
        superview, @"o1", [NSMutableArray array], @"o3", [NSArray arrayWithObject: @"public.text"], @"o6", nil];
    Scripted *s;
    NSView *v;

    // Versions 17-24: frame, bounds, superview, window, four objects, four flag bytes:
    // rotated, rotated or scaled, autoresizing mask, autoresizes subviews.
    s = scripted(@"NSView", 20, base);
    v = decodeWith(s, @"NSView", &reason);
    expectString(seq(s),
        @"obj v?NSView multi:f,f,f,f, multi:f,f,f,f, obj obj multi:@,@,@,@, multi:c, multi:c, multi:c, multi:c,",
        "NSView 17-24 sequence");
    expectString(describeView(v), @"frame={{1, 2}, {30, 40}} bounds={{5, 6}, {70, 80}} mask=0 autoresizesSubviews=0 subviews=0",
                 "NSView 17-24 geometry");
    {
        NSMutableDictionary *flags = [[base mutableCopy] autorelease];
        [flags setObject: N(0x15) forKey: @"c2"];
        [flags setObject: N(1) forKey: @"c3"];
        s = scripted(@"NSView", 24, flags);
        v = decodeWith(s, @"NSView", &reason);
        expect([v autoresizingMask] == 0x15, "NSView 17-24 autoresizing mask byte");
        expect([v autoresizesSubviews], "NSView 17-24 autoresizes subviews byte");
    }

    // Versions 25-40: a fifth flag byte, then the next key view and one more object.
    {
        NSMutableDictionary *with = [[base mutableCopy] autorelease];
        [with setObject: nextKey forKey: @"o7"];
        [with setObject: N(0x3f) forKey: @"c2"];
        s = scripted(@"NSView", 30, with);
        v = decodeWith(s, @"NSView", &reason);
        expectString(seq(s),
            @"obj v?NSView multi:f,f,f,f, multi:f,f,f,f, obj obj multi:@,@,@,@, multi:c, multi:c, multi:c, multi:c, multi:c, obj obj",
            "NSView 25-40 sequence");
        expect([v nextKeyView] == nextKey, "NSView 25-40 next key view");
        expect([v autoresizingMask] == 0x3f, "NSView 25-40 autoresizing mask byte");
        expect([v superview] == superview, "NSView 25-40 superview");
        expect([[v registeredDraggedTypes] count] == 1, "NSView 25-40 dragged types");
    }

    // Versions 1-16: a float, frame, bounds, two objects, then objects and two flag shorts.
    {
        NSDictionary *old = [NSDictionary dictionaryWithObjectsAndKeys:
            F(0), @"f0", F(1), @"f1", F(2), @"f2", F(30), @"f3", F(40), @"f4", F(5), @"f5", F(6), @"f6", F(70), @"f7",
            F(80), @"f8", [NSMutableArray array], @"o3", N(0xFC00), @"s1", nil];
        s = scripted(@"NSView", 10, old);
        v = decodeWith(s, @"NSView", &reason);
        expectString(seq(s), @"obj v?NSView multi:f, multi:f,f,f,f, multi:f,f,f,f, obj obj multi:@,s,s,@,", "NSView 1-16 sequence");
        expect([v autoresizingMask] == 0x3f, "NSView 1-16 autoresizing mask from the second short");
        expectString(describeView(v), @"frame={{1, 2}, {30, 40}} bounds={{5, 6}, {70, 80}} mask=63 autoresizesSubviews=0 subviews=0",
                     "NSView 1-16 geometry");
    }

    // Version 0 is read like version 1 and then refused.
    if (!onMac) {
        reason = nil;
        s = scripted(@"NSView", 0, base);
        v = decodeWith(s, @"NSView", &reason);
    } else {
        reason = nil;
        s = scripted(@"NSView", 0, base);
        @try {
            [[[NSView alloc] initWithCoder: s] release];
        } @catch (NSException *e) {
            reason = [e reason];
            expectString([e name], @"NSObjectInaccessibleException", "NSView version 0 exception name");
        }
    }
    expectString(reason, @"-[NSView initWithCoder:]: found NSView object version 0; cannot unarchive NSView versions less than 1.",
                 "NSView version 0 reason");

    // Version 41 (current): flags word, subviews and three more objects, frame, bounds, then four objects.
    s = scripted(@"NSView", 41, base);
    v = decodeWith(s, @"NSView", &reason);
    expectString(seq(s),
        @"obj v?NSView multi:i, multi:@,@,@,@,f,f,f,f,f,f,f,f, obj obj obj obj", "NSView 41 sequence");
    {
        // The flags word keeps the autoresizing mask in bits 24-29 and the subview flag in bit 23.
        NSDictionary *flags = [NSDictionary dictionaryWithObjectsAndKeys: N((6 << 24) | (1 << 23)), @"i0",
                               [NSMutableArray array], @"o1", F(1), @"f0", F(2), @"f1", F(30), @"f2", F(40), @"f3", nil];
        s = scripted(@"NSView", 41, flags);
        v = decodeWith(s, @"NSView", &reason);
        expect([v autoresizingMask] == 6, "NSView 41 autoresizing mask");
        expect([v autoresizesSubviews], "NSView 41 autoresizes subviews");
        expectString(NSStringFromRect([v frame]), @"{{1, 2}, {30, 40}}", "NSView 41 frame");
    }
}

static void testControl(void)
{
    NSString *reason = nil;
    NSCell *cell = [[[NSCell alloc] initTextCell: @"controlcell"] autorelease];
    NSDictionary *spec = [NSDictionary dictionaryWithObjectsAndKeys: cell, @"o9", N(7), @"i1", [NSMutableArray array], @"o1", nil];
    Scripted *s;
    NSControl *c;

    // Three layouts: tag, cell, flag short (0-16); tag, three flag bytes, cell (17-40); tag, two flag bytes, cell (41 on).
    NSString *viewPart = @"obj v?NSView multi:i, multi:@,@,@,@,f,f,f,f,f,f,f,f, obj obj obj obj v?NSControl ";
    s = scripted(@"NSControl", 10, spec);
    c = decodeWith(s, @"NSControl", &reason);
    expectString(seq(s), [viewPart stringByAppendingString: @"multi:i,@,s,"], "NSControl 0-16 sequence");
    expect([c tag] == 7 && [c cell] == cell, "NSControl 0-16 tag and cell");

    s = scripted(@"NSControl", 30, spec);
    c = decodeWith(s, @"NSControl", &reason);
    expectString(seq(s), [viewPart stringByAppendingString: @"multi:i, multi:c, multi:c, multi:c, obj"], "NSControl 17-40 sequence");
    expect([c tag] == 7 && [c cell] == cell, "NSControl 17-40 tag and cell");

    s = scripted(@"NSControl", 41, spec);
    c = decodeWith(s, @"NSControl", &reason);
    expectString(seq(s), [viewPart stringByAppendingString: @"multi:i,c,c,@,"], "NSControl 41 sequence");
    expect([c tag] == 7 && [c cell] == cell, "NSControl 41 tag and cell");
}

static void testActionCell(void)
{
    NSString *reason = nil;
    NSString *target = @"theTarget";
    NSDictionary *spec = [NSDictionary dictionaryWithObjectsAndKeys: N(3), @"i0", N(4), @"i1", N(9), @"i2", target, @"o4", @"other", @"o5", nil];
    NSString *cellPart = @"v?NSCell multi:i,i, multi:@,@,@,@, v?NSActionCell ";
    Scripted *s;
    NSActionCell *a;

    // From 17: tag, action, target and one more object, which does not come back as the control view.
    for (NSNumber *v in [NSArray arrayWithObjects: N(17), N(19), nil]) {
        s = scripted(@"NSActionCell", [v intValue], spec);
        a = decodeWith(s, @"NSActionCell", &reason);
        expectString(seq(s), [cellPart stringByAppendingString: @"multi:i,:, obj obj"], "NSActionCell 17 sequence");
        expect([a tag] == 9, "NSActionCell 17 tag");
        expectString(NSStringFromSelector([a action]), @"sel0:", "NSActionCell 17 action");
        expect([a target] == target, "NSActionCell 17 target");
        expect([a controlView] == nil, "NSActionCell 17 control view stays unset");
    }

    // Up to 16: target first, then tag and action.
    s = scripted(@"NSActionCell", 10, spec);
    a = decodeWith(s, @"NSActionCell", &reason);
    expectString(seq(s), [cellPart stringByAppendingString: @"obj multi:i,:,"], "NSActionCell 0-16 sequence");
    expect([a tag] == 9, "NSActionCell 0-16 tag");
    expect([a target] == target, "NSActionCell 0-16 target");
}

static void testCell(void)
{
    NSString *reason = nil;
    NSDictionary *spec = [NSDictionary dictionaryWithObjectsAndKeys: @"value", @"o0", nil];
    Scripted *s;
    id c;

    for (NSNumber *v in [NSArray arrayWithObjects: N(55), N(65), N(67), nil]) {
        s = scripted(@"NSCell", [v intValue], spec);
        c = decodeWith(s, @"NSCell", &reason);
        expectString(seq(s), @"v?NSCell multi:i,i, multi:@,@,@,@,", "NSCell sequence");
        expect(c != nil, "NSCell version accepted");
    }
    // 54 and below: NSInternalInconsistencyException from macOS, with this reason.
    for (NSNumber *v in [NSArray arrayWithObjects: N(0), N(40), N(54), nil]) {
        s = scripted(@"NSCell", [v intValue], spec);
        @try {
            [[[NSCell alloc] initWithCoder: s] release];
            expect(NO, "NSCell old version is rejected");
        } @catch (NSException *e) {
            expectString([e name], NSInternalInconsistencyException, "NSCell old version exception name");
            expectString([e reason],
                [NSString stringWithFormat: @"Cannot decode very old archived cells.  Archived cell is version %d.", [v intValue]],
                "NSCell old version reason");
        }
        expectString(seq(s), @"v?NSCell", "NSCell rejection reads nothing else");
    }
}

static id unarchive(NSString *dir, NSString *name)
{
    NSData *data = [NSData dataWithContentsOfFile: [dir stringByAppendingPathComponent: name]];
    if (data == nil) {
        return nil;
    }
    id result = nil;
    @try {
        result = [NSUnarchiver unarchiveObjectWithData: data];
    } @catch (NSException *e) {
        fprintf(stderr, "FAIL: unarchiving %s raised %s\n", [name UTF8String], [[e reason] UTF8String]);
        failures++;
    }
    return result;
}

static void testFixtures(NSString *dir)
{
    NSView *v = unarchive(dir, @"view.typedstream");
    expect([v isKindOfClass: [NSView class]], "view fixture class");
    expectString(describeView(v),
        @"frame={{1, 2}, {30, 40}} bounds={{0, 0}, {30, 40}} mask=6 autoresizesSubviews=0 subviews=1", "view fixture");
    expect([[v registeredDraggedTypes] count] == 1, "view fixture dragged types");

    NSControl *c = unarchive(dir, @"control.typedstream");
    expect([c isKindOfClass: [NSControl class]], "control fixture class");
    expectString(NSStringFromRect([c frame]), @"{{1, 2}, {30, 40}}", "control fixture frame");
    expect([c tag] == 7, "control fixture tag");
    expect([c autoresizingMask] == (NSViewWidthSizable | NSViewMinYMargin), "control fixture autoresizing mask");
    expect([[c cell] isKindOfClass: [NSActionCell class]], "control fixture cell class");
    expectString([[c cell] stringValue], @"cell", "control fixture cell value");
    expect([(NSActionCell *) [c cell] tag] == 5, "control fixture cell tag");
    expectString(NSStringFromSelector([(NSActionCell *) [c cell] action]), @"doIt:", "control fixture cell action");
}

int main(int argc, char **argv)
{
    NSAutoreleasePool *pool = [[NSAutoreleasePool alloc] init];
    {
        if (argc < 2) {
            fprintf(stderr, "usage: %s tests/fixtures/nonkeyed\n", argv[0]);
            return 2;
        }
        NSString *fixtures = [NSString stringWithUTF8String: argv[1]];
        onMac = argc > 2 && strcmp(argv[2], "--mac") == 0;

        [NSApplication sharedApplication];
        setCurrentVersions();
        // macOS 26 reads one layout for every version of these classes, so the
        // scripted checks (written for the 10.14 layouts) only apply elsewhere.
        if (!(onMac && argc > 3 && strncmp(argv[3], "macos-26", 8) == 0)) {
            testView();
            testControl();
            testActionCell();
            testCell();
        }
        NSArray *sets = onMac && argc > 3 ? [NSArray arrayWithObject: [NSString stringWithUTF8String: argv[3]]]
                                          : [NSArray arrayWithObjects: @"mojave-10.14.4", @"macos-26.7.3", nil];
        for (NSString *name in sets) {
            testFixtures([fixtures stringByAppendingPathComponent: name]);
        }
    }
    [pool drain];
    if (failures) {
        fprintf(stderr, "%d failure(s)\n", failures);
        return 1;
    }
    printf("OK\n");
    return 0;
}
