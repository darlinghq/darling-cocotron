// The stb JPEG decoder of Onyx2D (the decoder used when libjpeg is not
// available; it is always built into the library) must not leak a CFData per
// decoded image. Its initializer used to create the pixel data object twice and
// overwrite the first one. The test decodes through the decoder class directly
// (it is private) with a counting default CFAllocator and requires that every
// CF object allocated by a decode and release cycle is freed again.
#include <CoreFoundation/CoreFoundation.h>
#include <CoreGraphics/CoreGraphics.h>
#include <objc/message.h>
#include <objc/runtime.h>
#include <stdio.h>
#include <stdlib.h>

static long live;

static void *countAllocate(CFIndex size, CFOptionFlags hint, void *info) {
    live++;
    return malloc((size_t) size);
}

static void *countReallocate(void *ptr, CFIndex size, CFOptionFlags hint, void *info) {
    return realloc(ptr, (size_t) size);
}

static void countDeallocate(void *ptr, void *info) {
    live--;
    free(ptr);
}

