static void decodeOnce(Class decoderClass, CFDataRef jpeg) {
    CGDataProviderRef provider = CGDataProviderCreateWithCFData(jpeg);
    id decoder = ((id (*)(id, SEL))objc_msgSend)((id) decoderClass, sel_registerName("alloc"));
    decoder = ((id (*)(id, SEL, void *))objc_msgSend)(decoder, sel_registerName("initWithDataProvider:"), provider);
    if (decoder == nil) {
        fprintf(stderr, "FAIL decoder init returned nil\n");
        exit(1);
    }
    ((void (*)(id, SEL))objc_msgSend)(decoder, sel_registerName("release"));
    CGDataProviderRelease(provider);
}

int main(void) {
    Class decoderClass = objc_getClass("O2ImageDecoder_JPEG_stb");
    if (decoderClass == Nil) {
        fprintf(stderr, "FAIL class O2ImageDecoder_JPEG_stb not found\n");
        return 1;
    }
    CFDataRef jpeg = CFDataCreate(NULL, kRGBJPEG, sizeof(kRGBJPEG));

    CFAllocatorContext context = { 0, NULL, NULL, NULL, NULL, countAllocate, countReallocate, countDeallocate, NULL };
    CFAllocatorRef counting = CFAllocatorCreate(NULL, &context);
    CFAllocatorRef previous = CFAllocatorGetDefault();
    CFAllocatorSetDefault(counting);

    // Lazily created shared objects (colour spaces, class caches) are allocated
    // by the first decodes and stay alive; measure only after them.
    decodeOnce(decoderClass, jpeg);
    decodeOnce(decoderClass, jpeg);
    long before = live;
    for (int i = 0; i < 50; i++)
        decodeOnce(decoderClass, jpeg);
    long leaked = live - before;

    CFAllocatorSetDefault(previous);
    printf("CF allocations still live after 50 decodes: %ld\n", leaked);
    if (leaked != 0) {
        fprintf(stderr, "FAIL the stb decoder leaks %ld CF objects over 50 decodes\n", leaked);
        return 1;
    }
    puts("PASS stb decoder frees all CF objects it creates");
    return 0;
}
