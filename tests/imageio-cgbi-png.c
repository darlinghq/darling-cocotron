static int failures;

#define CHECK(cond, ...) do { if (cond) printf("PASS "); else { printf("FAIL "); failures++; } printf(__VA_ARGS__); printf("\n"); } while (0)

static CGImageRef decode(const unsigned char *bytes, size_t length)
{
	CFDataRef data = CFDataCreate(NULL, bytes, (CFIndex) length);
	CGImageSourceRef source = CGImageSourceCreateWithData(data, NULL);
	CFRelease(data);
	if (!source)
		return NULL;
	CGImageRef image = CGImageSourceCreateImageAtIndex(source, 0, NULL);
	CFRelease(source);
	return image;
}

/* The image's pixels as the data provider holds them (a copy, to be freed). */
static unsigned char *pixels(CGImageRef image, size_t *rowBytes)
{
	CFDataRef data = CGDataProviderCopyData(CGImageGetDataProvider(image));
	size_t n = (size_t) CFDataGetLength(data);
	unsigned char *copy = malloc(n);
	memcpy(copy, CFDataGetBytePtr(data), n);
	CFRelease(data);
	*rowBytes = CGImageGetBytesPerRow(image);
	return copy;
}

static int near(int a, int b) { return a - b <= 1 && b - a <= 1; }

static void check_small(void)
{
	static const unsigned char expected_row0[24] = {
		10, 20, 250, 255, 25, 10, 110, 128, 0, 0, 0, 0,
		130, 20, 160, 255, 85, 10, 65, 128, 0, 0, 0, 0 };
	CGImageRef cgbi = decode(cgbi_rgba_6x4, sizeof cgbi_rgba_6x4);
	CGImageRef plain = decode(plain_rgba_6x4, sizeof plain_rgba_6x4);
	CHECK(cgbi != NULL, "CgBI PNG decodes");
	CHECK(plain != NULL, "the same picture as an ordinary PNG decodes");
	if (!cgbi || !plain)
		return;
	CHECK(CGImageGetWidth(cgbi) == 6 && CGImageGetHeight(cgbi) == 4, "CgBI size is 6x4");
	CHECK(CGImageGetBitsPerComponent(cgbi) == 8 && CGImageGetBitsPerPixel(cgbi) == 32, "CgBI is 8 bits per component, 32 per pixel");
	CHECK(CGImageGetAlphaInfo(cgbi) == kCGImageAlphaPremultipliedLast, "CgBI alpha info is premultiplied last (%u)", (unsigned) CGImageGetAlphaInfo(cgbi));
	CHECK(CGImageGetAlphaInfo(plain) == kCGImageAlphaLast || CGImageGetAlphaInfo(plain) == kCGImageAlphaPremultipliedLast, "ordinary PNG with alpha has an alpha channel");
	size_t cb, pb;
	unsigned char *c = pixels(cgbi, &cb), *p = pixels(plain, &pb);
	CHECK(memcmp(c, expected_row0, sizeof expected_row0) == 0, "CgBI first row is premultiplied RGBA as on macOS");
	if (CGImageGetAlphaInfo(plain) == kCGImageAlphaPremultipliedLast) {
		int same = cb == pb;
		for (size_t y = 0; same && y < 4; y++)
			same = memcmp(c + y * cb, p + y * pb, 24) == 0;
		CHECK(same, "CgBI and ordinary PNG of the same picture give the same pixels");
	}
	free(c);
	free(p);
	CGImageRelease(cgbi);
	CGImageRelease(plain);
}

static void check_big(void)
{
	CGImageRef image = decode(cgbi_rgba_64x48, sizeof cgbi_rgba_64x48);
	CHECK(image != NULL, "64x48 CgBI PNG (several row filters) decodes");
	if (!image)
		return;
	CHECK(CGImageGetWidth(image) == 64 && CGImageGetHeight(image) == 48, "size is 64x48");
	size_t rb;
	unsigned char *px = pixels(image, &rb);
	int bad = 0;
	for (int y = 0; y < 48; y++)
		for (int x = 0; x < 64; x++) {
			int r = (4 * x + y) & 255, g = (5 * y) & 255, b = (x * y) & 255;
			int a = y < 24 ? 255 : (4 * x) & 255;
			/* the tool rounds the premultiplication itself: allow one step */
			const unsigned char *q = px + y * rb + x * 4;
			if (!near(q[0], (r * a + 127) / 255) || !near(q[1], (g * a + 127) / 255) ||
			    !near(q[2], (b * a + 127) / 255) || q[3] != a)
				bad++;
		}
	CHECK(bad == 0, "every pixel is the premultiplied source pixel (%d wrong)", bad);
	free(px);
	CGImageRelease(image);
}

/* macOS ImageIO may return a partly decoded picture for damaged data and we may
   return NULL; both are fine as long as nothing crashes and a returned image is
   the right size. */
static void expect_survives(const unsigned char *bytes, size_t length, const char *what)
{
	CGImageRef image = decode(bytes, length);
	CHECK(image == NULL || (CGImageGetWidth(image) == 6 && CGImageGetHeight(image) == 4), "%s: no crash, NULL or a 6x4 image", what);
	if (image)
		CGImageRelease(image);
}

static void check_damaged(void)
{
	size_t n = sizeof cgbi_rgba_6x4;
	unsigned char *copy = malloc(n);

	expect_survives(cgbi_rgba_6x4, n - 40, "truncated in the image data");

	/* image data replaced by junk of the same length (inflate fails) */
	memcpy(copy, cgbi_rgba_6x4, n);
	for (size_t i = 0; i + 4 < n; i++) {
		if (memcmp(copy + i, "IDAT", 4) == 0) {
			for (size_t j = i + 4; j < n - 16; j++)
				copy[j] = 0xff;
			break;
		}
	}
	expect_survives(copy, n, "corrupt image data");

	/* cut at chunk boundaries */
	expect_survives(cgbi_rgba_6x4, 24 + 25, "cut after IHDR");
	expect_survives(cgbi_rgba_6x4, 24, "cut after the first chunk");
	free(copy);
}

int main(void)
{
	check_small();
	check_big();
	check_damaged();
	printf("%s\n", failures ? "FAILED" : "PASS: CgBI PNG decoding");
	return failures != 0;
}
