static int failures;
#define CHECK(cond, ...) do { if (!(cond)) { printf("FAIL: " __VA_ARGS__); printf("\n"); failures++; } } while (0)

int main(void) {
    @autoreleasepool {
        NSData *data = [NSData dataWithBytes: kScrollViewWithTextTemplate length: sizeof(kScrollViewWithTextTemplate)];
        NSScrollView *scroll = nil;
        @try {
            scroll = [NSUnarchiver unarchiveObjectWithData: data];
        } @catch (NSException *e) {
            printf("FAIL: unarchive raised %s\n", [[e description] UTF8String]);
            return 1;
        }
        CHECK([scroll isKindOfClass: [NSScrollView class]], "root is %s", [[scroll className] UTF8String]);

        NSClipView *clip = [scroll contentView];
        NSTextView *text = [scroll documentView];
        CHECK([text isKindOfClass: [NSTextView class]], "document view is %s", [[text className] UTF8String]);
        CHECK([[clip subviews] count] == 1 && [[clip subviews] objectAtIndex: 0] == text, "clip view subviews %lu",
              (unsigned long) [[clip subviews] count]);
        CHECK([text superview] == clip, "text view superview is %s", [[[text superview] className] UTF8String]);
        CHECK([text enclosingScrollView] == scroll, "enclosingScrollView is %s", [[[text enclosingScrollView] className] UTF8String]);
        CHECK([text nextResponder] == clip, "next responder is %s", [[[text nextResponder] className] UTF8String]);
        CHECK([[text string] isEqualToString: @"Hello text"], "string '%s'", [[text string] UTF8String]);
        // The size is not compared: macOS keeps the archived 470x260 until the scroll view is laid out;
        // the clip view fits the document view when it is resized, and that must leave a usable width.
        CHECK([text frame].size.width > 0 && [text frame].size.height > 0, "frame %s", [NSStringFromRect([text frame]) UTF8String]);
        CHECK(NSEqualRects([scroll frame], NSMakeRect(20, 188, 487, 262)), "scroll frame %s", [NSStringFromRect([scroll frame]) UTF8String]);

        // The scroll view and the clip view also have each other as superview.
        CHECK([clip superview] == scroll, "clip superview");
        CHECK([[scroll verticalScroller] superview] == scroll, "scroller superview");

        // Leave without tearing the views down: macOS 10.14.4 raises while releasing a text view
        // that was unarchived this way (its clip view observer is not registered), which is not
        // what this test is about.
        printf(failures ? "FAILED\n" : "PASSED\n");
        fflush(stdout);
        _exit(failures ? 1 : 0);
    }
}
