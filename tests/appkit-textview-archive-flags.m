        expect([view isAutomaticQuoteSubstitutionEnabled] && [view isAutomaticDashSubstitutionEnabled],
               "quote and dash substitution are on");
        expect([view isAutomaticLinkDetectionEnabled] && [view isAutomaticDataDetectionEnabled], "link and data detection are on");
